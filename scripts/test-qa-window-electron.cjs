/* Real app preload, QA IPC authorization, native window and renderer synchronization. */
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os')
async function driver() {
  const { build } = require('esbuild'), { spawn } = require('node:child_process')
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'parity-qa-window-'))
  fs.symlinkSync(path.join(__dirname, '../node_modules'), path.join(dir, 'node_modules'), 'junction')
  const common = { bundle: true, platform: 'node', format: 'cjs', external: ['electron', 'sharp', 'nspell', 'dictionary-en'], define: { __PARITY_SUPABASE_URL__: '""', __PARITY_SUPABASE_KEY__: '""', __PARITY_VIEWER_URL__: '""' } }
  for (const [source, name] of [['src/main/qaChatWindow.ts', 'window'], ['src/main/qaAgent/index.ts', 'qa'], ['src/main/designStore.ts', 'designs'], ['src/preload/index.ts', 'preload']]) await build({ ...common, entryPoints: [path.join(__dirname, '..', source)], outfile: path.join(dir, name + '.cjs') })
  await build({ entryPoints: [path.join(__dirname, 'fixtures/qa-window.tsx')], outfile: path.join(dir, 'ui.js'), bundle: true, platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.svg': 'dataurl', '.png': 'dataurl' } })
  fs.writeFileSync(path.join(dir, 'ui.html'), '<!doctype html><html data-theme="parity"><meta charset="utf-8"><link rel="stylesheet" href="ui.css"><style>body{margin:0;font:14px Arial;background:var(--bg-app);color:var(--text-primary)}</style><div id="root"></div><script src="ui.js"></script></html>')
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const child = spawn(require('electron'), [__filename, '--smoke', dir], { env, windowsHide: true, stdio: 'inherit' })
  const timer = setTimeout(() => child.kill(), 120000)
  child.once('exit', code => { clearTimeout(timer); console.log('QA window artifacts:', dir); process.exitCode = code === 0 ? 0 : 1 })
}
async function smoke() {
  const { app, BrowserWindow, ipcMain } = require('electron')
  const dir = process.argv[process.argv.indexOf('--smoke') + 1]
  app.on('window-all-closed', () => {}); app.setPath('userData', path.join(dir, 'profile')); app.disableHardwareAcceleration(); await app.whenReady()
  const preload = path.join(dir, 'preload.cjs'), rendererFile = path.join(dir, 'ui.html')
  const host = new BrowserWindow({ show: false, width: 540, height: 780, webPreferences: { preload, sandbox: false, contextIsolation: true, backgroundThrottling: false } })
  const controller = require(path.join(dir, 'window.cjs')).registerQaChatWindow({ getMainWindow: () => host, preload, rendererFile })
  const designs = require(path.join(dir, 'designs.cjs')).createDesignStore(path.join(dir, 'designs'))
  const qa = require(path.join(dir, 'qa.cjs')).registerQaAgent({ getMainWindow: () => host, getChatWindow: controller.getWindow, getDesignStore: () => designs })
  ipcMain.handle('app:set-title-bar-overlay', (event, symbolColor) => { const window = BrowserWindow.fromWebContents(event.sender); if (window === controller.getWindow()) window.setTitleBarOverlay({ symbolColor }) })
  qa.attachMainWindow(host); controller.attachMainWindow(host)
  const run = (win, code) => win.webContents.executeJavaScript(code)
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))
  const until = async (check, name) => { for (let i = 0; i < 160; i++) { if (await check()) return; await sleep(50) } throw new Error('Timeout: ' + name) }
  const click = (win, selector) => run(win, `document.querySelector(${JSON.stringify(selector)}).click()`)
  const type = (win, text) => run(win, `const el = document.querySelector('textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(el, ${JSON.stringify(text)}); el.dispatchEvent(new Event('input',{bubbles:true}));`)
  await host.loadFile(rendererFile)
  await until(() => run(host, `!!window.__chat`), 'host initialized')
  await run(host, `__chat.addUserMessage('Keep this conversation'); __chat.handle({type:'text',text:'Already answered'}); __chat.setDraft('Unsent message','chat')`)
  await click(host, '[aria-label="Detach agent chat"]')
  await until(() => !!controller.getWindow(), 'window created')
  let detached = controller.getWindow()
  await until(() => run(detached, `!!document.querySelector('[aria-label="Dock agent chat"]')`), 'detached initialized')
  console.log('Detached chat opened')
  assert.equal(detached.isResizable(), true); assert.equal(detached.isMaximizable(), true)
  assert.equal(await run(host, `document.querySelector('.qa-chat') === null`), true, 'host panel relinquishes space')
  assert.equal(await run(detached, `document.querySelector('textarea').value`), 'Unsent message')
  assert.match(await run(detached, 'document.body.innerText'), /Already answered/)
  assert.equal(await run(detached, `getComputedStyle(document.querySelector('.qa-window-titlebar')).webkitAppRegion`), 'drag')
  const old = detached.getNormalBounds(); detached.setBounds({ ...old, x: old.x + 15, y: old.y + 15, width: 640, height: 650 })
  await until(() => run(detached, `innerWidth >= 620 && innerHeight < 680`), 'native resize')
  assert.equal(await run(detached, `document.querySelector('.qa-chat').getBoundingClientRect().bottom <= innerHeight+1`), true, 'composer fits resized window')
  console.log('Native bounds and chat layout verified')
  assert.equal((await run(detached, `electronAPI.qaTarget()`)).pageUrl, 'https://example.test/page', 'trusted detached IPC retains workspace target')
  await run(detached, `electronAPI.qaReportContext(null)`)
  assert.ok(await run(host, `electronAPI.qaTarget()`), 'detached renderer cannot replace workspace context')
  const other = new BrowserWindow({ show: false, webPreferences: { preload, sandbox: false, contextIsolation: true } }); await other.loadURL('about:blank')
  assert.equal(await run(other, `electronAPI.qaWindowDetach()`), false)
  assert.equal(await run(other, `electronAPI.qaTarget()`), null)
  await run(other, `electronAPI.qaWindowAction({type:'clear'})`); await sleep(50)
  assert.match(await run(detached, 'document.body.innerText'), /Already answered/, 'untrusted window cannot clear transcript')
  console.log('QA window authorization verified')
  host.webContents.send('qa:run:event', { type: 'started', agent: 'fixture', label: 'Fixture agent' })
  host.webContents.send('qa:run:event', { type: 'text', text: 'Live ', delta: true })
  host.webContents.send('qa:run:event', { type: 'text', text: 'answer', delta: true })
  host.webContents.send('qa:run:event', { type: 'usage', inputTokens: 21, outputTokens: 5 })
  await until(() => run(detached, `document.body.innerText.includes('Live answer')`), 'stream in detached window')
  await type(detached, 'Updated unsent message')
  await until(() => run(host, `__chat.getState().draft.input === 'Updated unsent message'`), 'draft mirror')
  await click(detached, '[id="qa-tab-findings"]')
  await until(() => run(host, `__chat.getState().draft.tab === 'findings'`), 'tab mirror')
  for (const theme of ['github-light', 'parity', 'rose-gold']) {
    await run(host, `__theme(${JSON.stringify(theme)})`)
    await until(() => run(detached, `document.documentElement.getAttribute('data-theme') === ${JSON.stringify(theme)}`), 'theme mirror')
  }
  await click(detached, '[id="qa-tab-chat"]'); await click(detached, '.qa-chat-actions button[title="Past chats and reviews"]')
  await until(() => run(host, `__opened.some(item => item.name === 'parity:open-qa-history')`), 'history route')
  console.log('Live transcript, draft, theme and history verified')
  fs.writeFileSync(path.join(dir, 'detached.png'), (await detached.webContents.capturePage()).toPNG())
  await click(detached, '[aria-label="Dock agent chat"]')
  await until(() => !controller.getWindow(), 'docked')
  await until(() => run(host, `!!document.querySelector('textarea')`), 'panel restored')
  assert.equal(await run(host, `document.querySelector('textarea').value`), 'Updated unsent message')
  assert.equal(await run(host, `__chat.getState().session.input`), 21, 'usage not duplicated')
  assert.equal(await run(host, `__chat.getState().running`), true, 'dock leaves run active')
  console.log('Docking verified')
  await click(host, '[aria-label="Detach agent chat"]'); await until(() => !!controller.getWindow(), 'reopened'); detached = controller.getWindow()
  await until(() => run(detached, `!!document.querySelector('.qa-chat')`), 'reopened initialized')
  assert.equal(detached.getNormalBounds().width, 640, 'restores native bounds')
  detached.close(); await until(() => !controller.getWindow(), 'native close docks')
  assert.equal(await run(host, `__chat.getState().running`), true)
  console.log('Native close verified')
  await click(host, '[aria-label="Detach agent chat"]'); await until(() => !!controller.getWindow(), 'last open'); detached = controller.getWindow()
  await until(() => run(detached, `!!document.querySelector('.qa-chat')`), 'last window ready')
  host.destroy(); await until(() => detached.isDestroyed(), 'host close cleans detached window')
  other.destroy(); console.log('QA detached window smoke passed'); app.exit(0)
}
if (process.argv.includes('--smoke')) smoke().catch(error => { console.error(error); require('electron').app.exit(1) })
else driver().catch(error => { console.error(error); process.exitCode = 1 })
